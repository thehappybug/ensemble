import { execFile } from 'node:child_process';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { promisify } from 'node:util';
import { afterEach, describe, expect, it } from 'vitest';
import { loadConfig } from '../src/config.js';
import { createRuntime } from '../src/daemon.js';
import { FakeRunner } from '../src/runner/FakeRunner.js';
import type { RunMeta } from '../src/types.js';
import { atomicWrite, requiredOutputs } from '../src/util.js';
import { initWorkspace } from '../src/workspace/commands.js';

const exec = promisify(execFile);
const roots: string[] = [];
afterEach(async () => { await Promise.all(roots.splice(0).map(root => rm(root, { recursive: true, force: true }))); });
const csv = [
  'company_name,product_name,website,hq_country,funding,one_liner',
  'Alpha Tools,Alpha Agent,https://alpha.example,US,Unknown,Synthetic company A',
  'Beta Tools,Beta Agent,https://beta.example,US,Unknown,Synthetic company B',
  '',
].join('\n');
const people = (key: string) => `coding-agents/companies/_each/people[${key}]`;
const direction = (key: string) => `coding-agents/companies/_each/direction[${key}]`;
const fit = (key: string) => `coding-agents/companies/_each/icp-fit[${key}]`;
const downstream = ['coding-agents/icp-ranking', 'coding-agents/outreach/sequence', 'coding-agents/outreach/send-drafts'];

function isAfter(runs: string[], later: string, earlier: string) {
  expect(runs.indexOf(earlier)).toBeGreaterThanOrEqual(0);
  expect(runs.indexOf(later)).toBeGreaterThan(runs.indexOf(earlier));
}

async function commitsFor(root: string, ids: string[], records: Record<string, { lastRun?: RunMeta }>) {
  const commits = ids.map(id => records[id]?.lastRun?.commit);
  expect(commits.every(Boolean)).toBe(true);
  expect(new Set(commits).size).toBe(ids.length);
  for (const id of ids) {
    const run = records[id].lastRun!;
    expect(run.status).toBe('completed');
    if (!run.inputs_commit) throw new Error(`Missing inputs_commit for ${id}: ${JSON.stringify(run)}`);
    expect(run.inputs_commit).toMatch(/^[a-f0-9]{40}$/);
    const { stdout } = await exec('git', ['show', '--format=%H', '--name-only', run.commit!], { cwd: root });
    expect(stdout.split('\n')[0]).toBe(run.commit);
    for (const output of Object.keys(run.outputs ?? {})) expect(stdout.split('\n')).toContain(output);
    const { stdout: ancestor } = await exec('git', ['merge-base', '--is-ancestor', run.inputs_commit!, run.commit!], { cwd: root });
    expect(ancestor).toBe('');
  }
  return commits as string[];
}

describe('example workspace cascade with real git history', () => {
  it('reruns only ICP synthesis after an edit, then only the new company chain after a CSV row is added', async () => {
    const root = await mkdtemp(path.join(os.tmpdir(), 'ensemble-cascade-'));
    roots.push(root);
    await initWorkspace(root, 'coding-agents-icp');
    const config = await loadConfig(root);
    config.git.auto_commit = true;
    config.scheduler.concurrency = 3;
    // Every generated byte comes from this node's own rendered prompt, item, and
    // declared inputs through its fingerprint. No live LLM or integration runs.
    const runner = new FakeRunner(async (node, ctx) => {
      for (const output of requiredOutputs(node)) {
        let content: string;
        if (output === 'coding-agents/top-10.csv') content = csv;
        else if (output.endsWith('.sources.json')) content = JSON.stringify({ simulated: true, basis: [] }) + '\n';
        else if (output.endsWith('.plan.json')) content = JSON.stringify({
          action: node.path, instance: null, fingerprint: node.fingerprint,
          planned_at: '2026-10-19T00:00:00Z', run_id: ctx.runId,
          summary: 'SIMULATED plan; no external calls', steps: [],
        }) + '\n';
        else content = `# SIMULATED ${node.id}\n\n${node.fingerprint}\n`;
        await atomicWrite(path.join(ctx.root, output), content);
      }
      return { summary: 'SIMULATED deterministic cascade fixture' };
    });
    const runtime = await createRuntime(root, { config, runner });
    try {
      await runtime.scheduler.run({ automatic: true });
      const initialRuns = [...runner.runs];
      expect(initialRuns).toHaveLength(10);
      expect(new Set(initialRuns).size).toBe(10);
      for (const key of ['alpha-tools', 'beta-tools']) {
        isAfter(initialRuns, fit(key), people(key));
        isAfter(initialRuns, fit(key), direction(key));
        isAfter(initialRuns, downstream[0], fit(key));
      }
      isAfter(initialRuns, downstream[1], downstream[0]);
      isAfter(initialRuns, downstream[2], downstream[1]);
      const initialCommits = await commitsFor(root, initialRuns, runtime.store.data.nodes);
      const previousResearch = new Map(runtime.scheduler.graph.nodes
        .filter(node => /\/(people|direction)\[/.test(node.id))
        .map(node => [node.id, runtime.store.data.nodes[node.id].lastRun!.runId]));

      runner.runs = [];
      const icp = path.join(root, 'context/icp.md');
      await writeFile(icp, `${await readFile(icp, 'utf8')}\nMust have a public changelog.\n`);
      await runtime.scheduler.run({ automatic: true });
      const cascade = [...runner.runs];
      expect([...cascade].sort()).toEqual([fit('alpha-tools'), fit('beta-tools'), ...downstream].sort());
      for (const key of ['alpha-tools', 'beta-tools']) isAfter(cascade, downstream[0], fit(key));
      isAfter(cascade, downstream[1], downstream[0]);
      isAfter(cascade, downstream[2], downstream[1]);
      for (const [id, runId] of previousResearch) expect(runtime.store.data.nodes[id].lastRun!.runId).toBe(runId);
      const cascadeCommits = await commitsFor(root, cascade, runtime.store.data.nodes);
      expect(cascadeCommits.some(commit => initialCommits.includes(commit))).toBe(false);
      expect(runtime.scheduler.graph.nodes.find(node => node.kind === 'action')?.status).toBe('awaiting-approval');

      runner.runs = [];
      const beforeAdding = new Map(Object.entries(runtime.store.data.nodes).map(([id, record]) => [id, record.lastRun?.runId]));
      const dataset = path.join(root, 'coding-agents/top-10.csv');
      const edited = `${await readFile(dataset, 'utf8')}Gamma Tools,Gamma Agent,https://gamma.example,US,Unknown,Synthetic company C\n`;
      await writeFile(dataset, edited);
      await runtime.scheduler.run({ automatic: true });
      const added = [...runner.runs];
      expect([...added].sort()).toEqual([people('gamma-tools'), direction('gamma-tools'), fit('gamma-tools'), ...downstream].sort());
      isAfter(added, fit('gamma-tools'), people('gamma-tools'));
      isAfter(added, fit('gamma-tools'), direction('gamma-tools'));
      isAfter(added, downstream[0], fit('gamma-tools'));
      isAfter(added, downstream[1], downstream[0]);
      isAfter(added, downstream[2], downstream[1]);
      for (const key of ['alpha-tools', 'beta-tools']) {
        for (const id of [people(key), direction(key), fit(key)]) {
          expect(runtime.store.data.nodes[id].lastRun!.runId).toBe(beforeAdding.get(id));
        }
      }
      expect(await readFile(dataset, 'utf8')).toBe(edited);
      expect(runtime.scheduler.graph.nodes.find(node => node.id === 'coding-agents/top-10')?.status).toBe('modified');
      await commitsFor(root, added, runtime.store.data.nodes);
      const { stdout: count } = await exec('git', ['rev-list', '--count', 'HEAD'], { cwd: root });
      expect(Number(count.trim())).toBeGreaterThan(initialRuns.length + cascade.length + added.length);
      runner.runs = [];
      await runtime.scheduler.run({ automatic: true });
      expect(runner.runs).toEqual([]);
    } finally {
      await runtime.close();
    }
  }, 30_000);
});
