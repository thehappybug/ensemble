import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import {existsSync} from 'node:fs';
import {mkdtemp,cp,readFile,writeFile,appendFile,mkdir,readdir} from 'node:fs/promises';
import {spawn} from 'node:child_process';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
// This smoke test only uses SimulationRunner; it never contacts model or app APIs.
const repo=fileURLToPath(new URL('..',import.meta.url)),require=createRequire(new URL('../package.json',import.meta.url));
const {chromium}=require('playwright'),YAML=require('yaml');
const root=await mkdtemp(path.join(os.tmpdir(),'ensemble-browser-'));
await cp(path.join(repo,'examples/coding-agents-icp'),root,{recursive:true});
const config=YAML.parse(await readFile(path.join(root,'ensemble.yaml'),'utf8'));
config.vars.row_limit=3;config.scheduler.debounce_ms=150;config.agents_md.summaries=false;
await writeFile(path.join(root,'ensemble.yaml'),YAML.stringify(config));
const port=17461+Math.floor(Math.random()*400),base=`http://127.0.0.1:${port}`;
const daemon=spawn(process.execPath,[path.join(repo,'dist/cli.js'),'dev','--simulate','--port',String(port)],{cwd:root,stdio:['ignore','pipe','pipe']});
let daemonOutput='';daemon.stdout.on('data',value=>daemonOutput+=value);daemon.stderr.on('data',value=>daemonOutput+=value);
const sleep=ms=>new Promise(resolve=>setTimeout(resolve,ms));
const get=async pathname=>{const res=await fetch(base+pathname,{signal:AbortSignal.timeout(3000)});if(!res.ok)throw new Error(`${pathname} ${res.status}: ${await res.text()}`);return res.json();};
async function waitFor(fn,label,timeout=90000){const started=Date.now();let last;while(Date.now()-started<timeout){if(daemon.exitCode!==null||daemon.signalCode!==null)throw new Error(`Daemon exited ${daemon.exitCode}: ${daemonOutput.slice(-3000)}`);try{const value=await fn();if(value)return value;}catch(error){last=error;}await sleep(200);}throw new Error(`Timed out: ${label}; ${last??''}; daemon: ${daemonOutput.slice(-3000)}`);}
const settled=graph=>graph.nodes.length>=13&&graph.nodes.every(node=>['fresh','awaiting-approval','modified'].includes(node.status));
let browser;
const result={root,base,checks:[],browserErrors:[],consoleErrors:[],requestFailures:[]};
const recordCheck=message=>{result.checks.push(message);console.log('[browser] '+message);};
const resultsFile=path.join(os.tmpdir(),'ensemble-browser-smoke-results.json');
try{
  await waitFor(()=>get('/api/graph'),'daemon HTTP ready');
  let executablePath=process.env.ENSEMBLE_CHROMIUM_PATH;
  if(!executablePath&&!existsSync(chromium.executablePath())){
    const cache=process.env.PLAYWRIGHT_BROWSERS_PATH??path.join(os.homedir(),'.cache/ms-playwright');
    const candidates=await readdir(cache).catch(()=>[]);
    for(const candidate of candidates.filter(name=>/^chromium_headless_shell-\d+$/.test(name)).sort((a,b)=>Number(b.split('-').at(-1))-Number(a.split('-').at(-1)))){const binary=path.join(cache,candidate,'chrome-headless-shell-linux64/chrome-headless-shell');if(existsSync(binary)){executablePath=binary;break;}}
  }
  browser=await chromium.launch({headless:true,...(executablePath?{executablePath}:{}),args:['--no-sandbox'],timeout:15000});
  const page=await browser.newPage({viewport:{width:1720,height:1100},deviceScaleFactor:1});
  page.on('pageerror',error=>result.browserErrors.push(error.message));
  page.on('console',message=>{if(message.type()==='error')result.consoleErrors.push(message.text());});
  page.on('requestfailed',request=>{if(!request.url().includes('/api/events'))result.requestFailures.push({url:request.url(),failure:request.failure()?.errorText});});
  await page.goto(base,{waitUntil:'domcontentloaded'});
  await page.getByRole('heading',{name:'Research flow.'}).waitFor();
  await page.getByText('SIMULATED',{exact:true}).first().waitFor();
  let graph=await waitFor(async()=>{const graph=await get('/api/graph');return settled(graph)?graph:false;},'initial simulated pipeline');
  assert.equal(graph.nodes.length,13);assert.equal(graph.simulated,true);assert.equal(graph.costs.llm+graph.costs.parallel,0);
  recordCheck('initial 13-node simulated graph + zero paid cost');
  await page.locator('.graph-node-group').first().waitFor();
  assert.equal(await page.locator('.graph-node-source').count(),3);
  const original=Object.fromEntries(graph.nodes.map(node=>[node.id,node.lastRun?.runId]));
  await page.getByRole('button',{name:'Pause auto-run',exact:true}).click();
  await waitFor(async()=>!!(await get('/api/graph')).paused,'pause');
  await appendFile(path.join(root,'context/icp.md'),'\nBrowser E2E criterion: must publish a public changelog.\n');
  await waitFor(async()=>{const next=await get('/api/graph');return next.nodes.filter(node=>node.status==='stale').length>=6?next:false;},'paused stale wave');
  await page.locator('.graph-state-stale').first().waitFor();
  recordCheck('editor ICP change produces visible stale wave while paused');
  await page.getByRole('button',{name:'Resume auto-run',exact:true}).click();
  graph=await waitFor(async()=>{const next=await get('/api/graph');return settled(next)&&next.nodes.filter(node=>node.id.includes('/icp-fit[')).every(node=>node.lastRun?.runId!==original[node.id])?next:false;},'reactive ICP cascade');
  const changed=graph.nodes.filter(node=>node.lastRun?.runId!==original[node.id]).map(node=>node.id);
  assert.equal(changed.length,6);assert(changed.every(id=>id.includes('/icp-fit[')||/icp-ranking|sequence|send-drafts/.test(id)));
  recordCheck('exact six-step ICP cascade; people/direction research runIds unchanged');
  await page.locator('.graph-node-group').filter({hasText:'icp fit'}).click();
  await page.getByRole('button',{name:'Sample Agent 1, fresh',exact:true}).click();
  await page.getByRole('dialog').waitFor();
  await page.getByRole('button',{name:/^Inputs/}).click();
  await page.locator('.input-row').first().waitFor();
  await page.getByRole('button',{name:'Outputs',exact:true}).click();
  await page.locator('.drawer .markdown').waitFor();
  await page.getByRole('button',{name:'History',exact:true}).click();
  await page.locator('.run-row').nth(1).waitFor();
  assert(await page.locator('.run-row .chip').filter({hasText:/git /}).count()>=2);
  await page.getByRole('button',{name:'Close node details',exact:true}).click();
  recordCheck('native graph expansion, node Inputs/Outputs/History drawer with real git commits');
  const beforeNew=Object.fromEntries(graph.nodes.map(node=>[node.id,node.lastRun?.runId]));
  await appendFile(path.join(root,'coding-agents/top-10.csv'),'Browser Agent,Browser Test,https://example.com/browser,Simulated,Unknown,Synthetic browser smoke company\n');
  graph=await waitFor(async()=>{const next=await get('/api/graph');return next.nodes.length===16&&settled(next)&&next.nodes.some(node=>node.id.includes('[browser-agent]')&&node.status==='fresh')?next:false;},'CSV new row cascade');
  const oldResearch=graph.nodes.filter(node=>/\/(people|direction|icp-fit)\[/.test(node.id)&&!node.id.includes('[browser-agent]'));
  assert(oldResearch.every(node=>node.lastRun?.runId===beforeNew[node.id]));
  recordCheck('CSV row adds exactly three new per-company nodes; existing instances untouched');
  await page.getByRole('button',{name:'Approvals 1',exact:true}).click();
  await page.getByText('SIMULATED plan · all execution stays simulated.',{exact:true}).waitFor();
  assert.equal(await page.locator('.email-card').count(),3);assert.equal(await page.locator('.ticket-card').count(),1);
  await page.getByRole('button',{name:'Approve dry run',exact:true}).click();
  await page.getByText('SIMULATED receipt',{exact:true}).first().waitFor();
  let review=await get('/api/actions/'+encodeURIComponent('coding-agents/outreach/send-drafts'));
  assert.equal(review.receipt.executions.at(-1).dry_run,true);assert.equal(review.receipt.executions.at(-1).steps.length,4);
  await page.getByRole('button',{name:'Approve dry run',exact:true}).click();
  await waitFor(async()=>{const review=await get('/api/actions/'+encodeURIComponent('coding-agents/outreach/send-drafts'));return review.receipt.executions.length===2?review:false;},'idempotent second approval');
  review=await get('/api/actions/'+encodeURIComponent('coding-agents/outreach/send-drafts'));
  assert(review.receipt.executions.at(-1).steps.every(step=>step.status==='skipped'));
  recordCheck('UI exact-plan approval: 3 simulated Gmail drafts +1 ticket; second approval idempotently skips all');
  await page.getByRole('button',{name:'Files',exact:true}).click();
  await waitFor(async()=>{const list=await get('/api/graph');return list.files.includes('coding-agents/AGENTS.md');},'idle librarian AGENTS');
  await page.getByRole('button',{name:'Refresh workspace',exact:true}).click();
  await page.getByRole('textbox',{name:'Find a workspace file',exact:true}).fill('coding-agents/AGENTS.md');
  await page.locator('.file-row').filter({hasText:'coding-agents/AGENTS.md'}).click();
  await page.locator('.file-viewer .markdown').getByText('Purpose:',{exact:false}).waitFor();
  await page.locator('.file-viewer .markdown a').filter({hasText:'top-10.prompt.md'}).first().click();
  await waitFor(async()=> (await page.locator('.file-viewer-header .mono').textContent())==='coding-agents/top-10.prompt.md','AGENTS relative file link');
  recordCheck('read-only files + generated AGENTS relative links open actual prompt');
  await page.getByRole('button',{name:'Activity',exact:true}).click();
  await page.getByText('Run completed',{exact:true}).first().waitFor();
  assert(await page.locator('.commit-label').count()>0);
  recordCheck('activity feed includes real per-run commit history');
  await page.getByRole('button',{name:'Flow',exact:true}).click();
  await page.getByRole('button',{name:'Refresh workspace',exact:true}).click();
  await sleep(600);
  await mkdir(path.join(repo,'docs/assets'),{recursive:true});
  await page.screenshot({path:path.join(repo,'docs/assets/browser-graph.png'),fullPage:true});
  result.screenshot='docs/assets/browser-graph.png';
  assert.deepEqual(result.browserErrors,[],'Browser runtime errors');
  assert.deepEqual(result.consoleErrors,[],'Browser console errors');
  assert.deepEqual(result.requestFailures.filter(item=>item.failure!=='net::ERR_ABORTED'),[],'Unexpected failed requests');
  const meta=await get('/api/graph');result.finalNodes=meta.nodes.length;result.finalStates=Object.fromEntries([...new Set(meta.nodes.map(node=>node.status))].map(status=>[status,meta.nodes.filter(node=>node.status===status).length]));
  await writeFile(resultsFile,JSON.stringify(result,null,2));
  console.log(JSON.stringify(result,null,2));
}catch(error){result.error=error.stack??String(error);result.daemonOutput=daemonOutput.slice(-5000);await writeFile(resultsFile,JSON.stringify(result,null,2));console.error(JSON.stringify(result,null,2));process.exitCode=1;}
finally{
  await browser?.close();
  if(daemon.exitCode===null&&daemon.signalCode===null)await new Promise(resolve=>{
    const timeout=setTimeout(()=>{daemon.kill('SIGKILL');resolve();},10000);
    daemon.once('exit',()=>{clearTimeout(timeout);resolve();});
    daemon.kill('SIGTERM');
  });
}
